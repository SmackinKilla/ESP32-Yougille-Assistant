enum WeatherIcon {
    ICON_CLEAR,
    ICON_SCATTERED_CLOUDS,
    ICON_RAIN,
    ICON_SNOW,
    ICON_MIST,
    ICON_UNKNOWN
};


WeatherIcon getIconFromCode(int code) {
    if (code >= 300 && code < 400) return ICON_RAIN;       
    if (code >= 500 && code < 600) return ICON_RAIN;
    if (code >= 600 && code < 700) return ICON_SNOW;
    if (code >= 700 && code < 800) return ICON_MIST;
    if (code == 800) return ICON_CLEAR;
    if (code == 802) return ICON_SCATTERED_CLOUDS;
    if (code >= 803) return ICON_SCATTERED_CLOUDS;
    return ICON_UNKNOWN;
}

const unsigned char* getIconBitmap(WeatherIcon icon) {
    switch (icon) {
        case ICON_CLEAR: return icon_clear;
        case ICON_SCATTERED_CLOUDS: return icon_scattered_clouds;
        case ICON_RAIN: return icon_rain;
        case ICON_SNOW: return icon_snow;
        case ICON_MIST: return icon_mist;
        default: return icon_clear;
    }
}